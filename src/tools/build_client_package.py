def main():
    gui = os.path.join(DIST, GUI_EXE)
    cli = os.path.join(DIST, CLI_EXE)
    for p, hint in ((gui, "窗口版"), (cli, "命令行版")):
        if not os.path.exists(p):
            print(f"缺少 dist/{os.path.basename(p)}（{hint}），请先编译：", file=sys.stderr)
            print(f'  go build -trimpath -ldflags="-s -w" -o dist/{CLI_EXE} ./cmd/collector',
                  file=sys.stderr)
            print(f'  go build -trimpath -ldflags="-s -w -H=windowsgui -X main.defaultGUIMode=true" '
                  f'-o "dist/{GUI_EXE}" ./cmd/collector', file=sys.stderr)
            return 1

    if os.path.isdir(PKG):
        shutil.rmtree(PKG)
    os.makedirs(PKG)

    shutil.copy2(gui, os.path.join(PKG, GUI_EXE))
    shutil.copy2(cli, os.path.join(PKG, CLI_EXE))

    # 离线复查工具（可选）：有就带上，没有不算失败。
    scan = os.path.join(DIST, "signonscan.exe")
    if os.path.exists(scan):
        shutil.copy2(scan, os.path.join(PKG, "signonscan.exe"))
    else:
        print("提示：dist/signonscan.exe 不存在，本次不打包离线复查工具",
              file=sys.stderr)

    cfg = json.dumps(CAPTURE_JSON, indent=2, ensure_ascii=False)
    with open(os.path.join(PKG, "capture.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(cfg + "\n")

    # 地图底图：<exe>/maps/<地图ID>/overview.png。
    #
    # 🔴 必须随包发，但**不能编进 exe**：
    #   · 这些是第三方美术资产（cs2_webradar，MIT © 2021 Lexogrine），
    #     混进二进制里既不好追溯也不好替换；
    #   · 放在外部目录，用户想换图/加图直接丢文件就行，不用重编译。
    # 目录不存在是允许的：那时雷达页会退回内嵌的数据轮廓图，并写明「不是官方贴图」。
    maps_src = os.path.join(DIST, "maps")
    maps_n = 0
    if os.path.isdir(maps_src):
        maps_dst = os.path.join(PKG, "maps")
        shutil.copytree(maps_src, maps_dst)
        maps_n = sum(len(fs) for _, _, fs in os.walk(maps_dst))
        n_dir = sum(1 for e in os.listdir(maps_dst) if os.path.isdir(os.path.join(maps_dst, e)))
        print(f"地图底图 : {n_dir} 张图 / {maps_n} 个文件")
    else:
        print("提示：dist/maps 不存在，本次不带底图（雷达页会显示数据轮廓图）",
              file=sys.stderr)

    with open(os.path.join(PKG, "使用说明.txt"), "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write(README)

    zip_path = os.path.join(DIST, "cs2radar-client.zip")
    if os.path.exists(zip_path):
        os.remove(zip_path)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        # 🔴 必须递归：maps/ 是多层目录，只 listdir 顶层的话
        # z.write(目录) 只会写一条目录项，里面的 PNG 一个都进不去 ——
        # 包看起来正常，装到用户机器上却没有一张底图。
        for dirpath, _, filenames in os.walk(PKG):
            for fn in sorted(filenames):
                abs_p = os.path.join(dirpath, fn)
                rel = os.path.relpath(abs_p, PKG).replace("\\", "/")
                z.write(abs_p, f"cs2radar-client/{rel}")

    def sha(p):
        return hashlib.sha256(open(p, "rb").read()).hexdigest()

    print("包目录 :", PKG)
    print("压缩包 :", zip_path, os.path.getsize(zip_path), "bytes")
    for name in sorted(os.listdir(PKG)):
        p = os.path.join(PKG, name)
        if name.lower().endswith(".exe"):
            print(f"{name} sha256:", sha(p))
    print("zip        sha256:", sha(zip_path))
    print("雷达链接 :", radar_url(DEFAULT_SESSION))
    return 0


if __name__ == "__main__":
    sys.exit(main())
